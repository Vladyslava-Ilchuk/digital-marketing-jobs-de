def save_excel(df, path):
    """
    Save as .xlsx instead of .csv. This sidesteps two problems entirely:
    - no delimiter guessing (Excel sometimes assumes ',' even when the
      file uses ';', which splits nested-dict text like arbeitsort across
      the wrong columns)
    - no encoding issues with German umlauts (ä, ö, ü, ß) - .xlsx stores
      text natively, there is no CSV encoding/BOM to get wrong
    Requires openpyxl (already installed in Google Colab by default).
    """
    df.to_excel(path, index=False, engine="openpyxl")


