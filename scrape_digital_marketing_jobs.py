# STEP 4. CLEANING
# ---------------------------------------------------------------------------

def clean_jobs(df):
    """
    - removes exact duplicates by refnr
    - removes rows without a title or without a description
    - keeps only postings published on/after MIN_PUBLISHED_DATE (safety net;
      the API's own 'veroeffentlichtseit' filter already restricts this
      during collection, this just double-checks it)
    - removes *logical* duplicates: the same employer reposting the exact
      same title over and over under a different refnr - keeps the most
      recently published copy of each (employer, title) pair
    - normalizes whitespace in text columns
    - adds level, hard_skills, soft_skills based on skill_descriptions
    """
    df = df.copy()

    df = df.drop_duplicates(subset="refnr")
    df = df.dropna(subset=["titel", "refnr"])
    df = df[df["skill_descriptions"].astype(str).str.strip().astype(bool)]

    for col in ["titel", "arbeitgeber", "city", "bundesland"]:
        if col in df.columns:
            df[col] = df[col].astype(str).str.strip()

    # safety-net date filter
    published_dt = pd.to_datetime(df["published"], errors="coerce")
    df = df[published_dt >= pd.Timestamp(MIN_PUBLISHED_DATE)]
    published_dt = published_dt[df.index]

    # logical dedup: same employer + same title posted repeatedly.
    # sort so the newest posting comes first, then keep only the first
    # occurrence of each (employer, title) combination.
    df = df.assign(_published_dt=published_dt)
    df = df.sort_values("_published_dt", ascending=False)
    dedup_key = (
        df["arbeitgeber"].str.lower().str.strip() + "||" +
        df["titel"].str.lower().str.strip()
    )
    df = df[~dedup_key.duplicated(keep="first")]
    df = df.drop(columns="_published_dt")

    df["level"] = df.apply(
        lambda row: extract_level(row["titel"], row["skill_descriptions"]), axis=1
    )
    df["hard_skills"] = df["skill_descriptions"].apply(
        lambda text: extract_skills(text, HARD_SKILLS_DE)
    )
    df["soft_skills"] = df["skill_descriptions"].apply(
        lambda text: extract_skills(text, SOFT_SKILLS_DE)
    )

    return df.reset_index(drop=True)


def select_final_columns(df):
    """Keeps only the columns from FINAL_COLUMNS, in the given order."""
    for col in FINAL_COLUMNS:
        if col not in df.columns:
            df[col] = ""
    return df[FINAL_COLUMNS]


